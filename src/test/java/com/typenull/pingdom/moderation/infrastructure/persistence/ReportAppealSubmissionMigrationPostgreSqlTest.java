package com.typenull.pingdom.moderation.infrastructure.persistence;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

@Tag("postgres-integration")
@Tag("migration")
@Testcontainers
class ReportAppealSubmissionMigrationPostgreSqlTest {

    @Container
    private static final PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:16-alpine");

    @BeforeEach
    void prepareAppealTable() throws Exception {
        try (Connection connection = postgres.createConnection(""); Statement statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS report_appeal");
            // V10의 동일 키·상태·원문을 구성하여 이 migration의 제약과 데이터 보존만 검증합니다.
            statement.execute("""
                    CREATE TABLE report_appeal (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        report_id BIGINT NOT NULL,
                        appellant_user_id BIGINT NOT NULL,
                        status VARCHAR(20) NOT NULL,
                        reason VARCHAR(500) NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE INDEX idx_report_appeal_report_appellant_status
                    ON report_appeal (report_id, appellant_user_id, status)
                    """);
        }
    }

    @Test
    void restrictsOnlySubmittedPairAndAllowsResubmissionAfterCompletion() throws Exception {
        try (Connection connection = postgres.createConnection(""); Statement statement = connection.createStatement()) {
            insert(statement, 1, 2, "SUBMITTED", "pending");
            insert(statement, 1, 2, "APPROVED", "approved history");
            insert(statement, 1, 2, "REJECTED", "rejected history");

            applyMigration(connection);

            assertThatThrownBy(() -> insert(statement, 1, 2, "SUBMITTED", "duplicate"))
                    .isInstanceOfSatisfying(SQLException.class,
                            exception -> assertThat(exception.getSQLState()).isEqualTo("23505"));
            insert(statement, 1, 3, "SUBMITTED", "another appellant");
            insert(statement, 2, 2, "SUBMITTED", "another report");
            statement.executeUpdate("UPDATE report_appeal SET status = 'REJECTED' WHERE reason = 'pending'");
            insert(statement, 1, 2, "SUBMITTED", "resubmitted");
            assertThatThrownBy(() -> statement.executeUpdate(
                    "UPDATE report_appeal SET status = 'SUBMITTED' WHERE reason = 'approved history'"))
                    .isInstanceOfSatisfying(SQLException.class,
                            exception -> assertThat(exception.getSQLState()).isEqualTo("23505"));

            try (ResultSet result = statement.executeQuery("SELECT COUNT(*) FROM report_appeal")) {
                assertThat(result.next()).isTrue();
                assertThat(result.getLong(1)).isEqualTo(6);
            }
            try (ResultSet result = statement.executeQuery("""
                    SELECT indexdef FROM pg_indexes WHERE indexname = 'uq_report_appeal_submitted'
                    """)) {
                assertThat(result.next()).isTrue();
                assertThat(result.getString(1)).contains("UNIQUE", "report_id, appellant_user_id", "SUBMITTED");
            }
        }
    }

    @Test
    void refusesExistingDuplicatesWithoutChangingTheirStatusOrEvidence() throws Exception {
        try (Connection connection = postgres.createConnection(""); Statement statement = connection.createStatement()) {
            insert(statement, 1, 2, "SUBMITTED", "first evidence");
            insert(statement, 1, 2, "SUBMITTED", "second evidence");

            assertThatThrownBy(() -> applyMigration(connection))
                    .hasStackTraceContaining("duplicate SUBMITTED report appeals require an explicit preservation policy");

            try (ResultSet result = statement.executeQuery(
                    "SELECT status, reason FROM report_appeal ORDER BY id")) {
                assertThat(result.next()).isTrue();
                assertThat(result.getString(1)).isEqualTo("SUBMITTED");
                assertThat(result.getString(2)).isEqualTo("first evidence");
                assertThat(result.next()).isTrue();
                assertThat(result.getString(1)).isEqualTo("SUBMITTED");
                assertThat(result.getString(2)).isEqualTo("second evidence");
                assertThat(result.next()).isFalse();
            }
            try (ResultSet result = statement.executeQuery(
                    "SELECT COUNT(*) FROM pg_indexes WHERE indexname = 'uq_report_appeal_submitted'")) {
                assertThat(result.next()).isTrue();
                assertThat(result.getLong(1)).isZero();
            }
        }
    }

    private void applyMigration(Connection connection) throws SQLException, IOException {
        String sql = new ClassPathResource("db/migration/V177__prevent_duplicate_submitted_report_appeals.sql")
                .getContentAsString(StandardCharsets.UTF_8);
        connection.setAutoCommit(false);
        try (Statement statement = connection.createStatement()) {
            // PostgreSQL JDBC가 dollar quote를 해석하도록 DO 블록을 포함한 원문을 그대로 전달합니다.
            statement.execute(sql);
            connection.commit();
        } catch (SQLException exception) {
            connection.rollback();
            throw exception;
        } finally {
            connection.setAutoCommit(true);
        }
    }

    private void insert(Statement statement, long reportId, long appellantId, String status, String reason)
            throws SQLException {
        statement.executeUpdate("INSERT INTO report_appeal (report_id, appellant_user_id, status, reason) VALUES ("
                + reportId + ", " + appellantId + ", '" + status + "', '" + reason + "')");
    }
}
